# pedimos los tres numeros enteros al usuario
numero1 = int(input("ingresa el primer numero entero:" ))
numero2 = int(input("ingresa el segundo numero entero:" ))
numero3 = int(input("ingresa el tercer numero entero" ))

# calculamos el promedio 
promedio = (numero1 + numero2 + numero3) / 3
# mostramos el resultado
print("el valor de medio de los tres numeros es:", promedio)